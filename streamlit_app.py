def extract_final_answer(agent_response):
    final_answer_marker = "Final Answer:"
    if final_answer_marker in agent_response:
        final_answer = agent_response.split(final_answer_marker)[-1].strip().replace("```", "")
        return final_answer
    return "Sorry, the context is not clear enough to answer."

