    def on_chain_error(self, error, *, run_id, parent_run_id = None, **kwargs: Any):
        logging.info("on_chain_error")
        logging.info(error)
        if 'Final Answer' not in self.current_text:
            self.placeholder.markdown('Sorry, the context is not clear enough to answer or invalid format in answer.')
        pass

    def on_agent_finish(self, finish, *, run_id, parent_run_id = None, **kwargs: Any):
        # logging.info(f"on_agent_finish {finish.return_values['output']}")
        if 'Final Answer' not in self.current_text:
            self.placeholder.markdown('Sorry, the context is not clear enough to answer.')
        
    def on_llm_new_token(self, token: str, **kwargs: Any) -> None:
        """Called every time a new token is generated by the language model."""
